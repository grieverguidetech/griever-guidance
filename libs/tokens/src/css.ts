import type { buildRecipes, buildRoles, Gradient, Primitives, Shadow } from './v2/index.js';

/** The v1 values the web theme is built from. */
export interface WebThemeInput {
  colors: Readonly<Record<string, string>>;
  fontSerifStack: string;
  /** Pixels, keyed like the `--space-*` custom properties. */
  spacing: Readonly<Record<string, number>>;
  /** Pixels, keyed like the `--radius-*` custom properties. */
  radius: Readonly<Record<string, number>>;
  /** When given, the v2 role and recipe vars are added after the v1 ones. Leaves v1 text unchanged. */
  v2?: WebV2Input;
}

/** The parts of v2 the web theme reads. */
export interface WebV2Input {
  primitives: Pick<Primitives, 'font' | 'border'>;
  roles: ReturnType<typeof buildRoles>;
  recipes: ReturnType<typeof buildRecipes>;
}

/** Top of every generated token CSS file (web theme and marketing vars). */
export const generatedHeader = `/* GENERATED by tools/scripts/generate-token-css.mjs from libs/tokens. Do not edit.
   Change libs/tokens, then run: pnpm nx run tokens:generate-css */

`;

/** The colour family of a key: its name without a three-digit shade, or `base` when it has none. */
function family(name: string): string {
  const match = /^(.+)-\d{3}$/.exec(name);
  return match ? match[1] : 'base';
}

/** `--font-serif`, then the colours, with a blank line between colour families. */
export function themeLines(input: WebThemeInput): string[] {
  const lines = [`  --font-serif: ${input.fontSerifStack};`];
  let previous: string | undefined;
  for (const [name, value] of Object.entries(input.colors)) {
    const current = family(name);
    if (previous !== current) {
      lines.push('');
    }
    previous = current;
    lines.push(`  --color-${name}: ${value};`);
  }
  return lines;
}

/** `--space-*`, a blank line, then `--radius-*`, in pixels. */
export function rootLines(input: WebThemeInput): string[] {
  const lines = Object.entries(input.spacing).map(([name, value]) => `  --space-${name}: ${value}px;`);
  lines.push('');
  for (const [name, value] of Object.entries(input.radius)) {
    lines.push(`  --radius-${name}: ${value}px;`);
  }
  return lines;
}

/** One CSS rule with the given lines as its body. */
export function block(selector: string, lines: readonly string[]): string {
  return `${selector} {\n${lines.join('\n')}\n}\n`;
}

/**
 * The CSS text for the web theme: an `@theme` block and a `:root` block. Pure: the same input
 * always gives the same text, in the input's key order. Tailwind reads `@theme`; `:root` holds
 * the plain custom properties it does not turn into utilities.
 */
export function toWebThemeCss(input: WebThemeInput): string {
  const theme = input.v2 ? [...themeLines(input), '', ...webV2ThemeLines(input.v2)] : themeLines(input);
  const root = input.v2 ? [...rootLines(input), '', ...webV2RootLines(input.v2)] : rootLines(input);
  return `${block('@theme', theme)}\n${block(':root', root)}`;
}

/** The whole text of theme.generated.css: header plus theme. */
export function toGeneratedFile(input: WebThemeInput): string {
  return generatedHeader + toWebThemeCss(input);
}

/** The parts of v2 the marketing page reads. */
export interface MarketingInput {
  roles: ReturnType<typeof buildRoles>;
  recipes: ReturnType<typeof buildRecipes>;
}

/** `linear-gradient(120deg, a, b, c)` at the swirl's own angle. */
function gradientCss(swirl: Gradient): string {
  return `linear-gradient(${swirl.angle}deg, ${swirl.stops.join(', ')})`;
}

/** `conic-gradient(a, b, c, a)`: the stops round the circle, the last blending back into the first (as mobile's ConicSwirl does). */
function conicCss(stops: readonly string[]): string {
  return `conic-gradient(${[...stops, stops[0]].join(', ')})`;
}

/** Degrees of one pass: settle time of a full turn, never more than one turn (the cap mobile's ConicSwirl uses). */
function oneTurnDeg(settleMs: number, spinMs: number): string {
  return `${(360 * settleMs) / Math.max(spinMs, settleMs)}deg`;
}

/** `0 1px 9px rgba(...)`, one entry per shadow, joined by commas. */
function shadowCss(shadows: readonly Shadow[]): string {
  return shadows.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.color}`).join(', ');
}

/** The `--gg-*` lines for marketing, grouped by what they style. */
export function marketingLines({ roles, recipes }: MarketingInput): string[] {
  const { primary, secondary } = recipes.button;
  const card = recipes.card;
  const lines: Array<[string, string]> = [
    ['page', roles.page.color],
    ['glow-sun', roles.page.glows.topRight],
    ['glow-sky', roles.page.glows.bottomLeft],
    ['ink', roles.ink],
    ['font', `'${roles.body.family}'`],
    ['heading', roles.heading.color],
    ['heading-weight', String(roles.heading.weight)],
    ['eyebrow', roles.eyebrow.color],
    ['eyebrow-size', `${roles.eyebrow.size}px`],
    ['eyebrow-tracking', `${roles.eyebrow.tracking}em`],
    ['link', roles.link],
    ['muted', roles.muted],
    ['divider', roles.divider],
    ['primary-bg', gradientCss(primary.swirl)],
    ['primary-text', primary.text.color],
    ['primary-weight', String(primary.text.weight)],
    ['primary-border', `${primary.border.width}px solid ${primary.border.color}`],
    ['primary-shadow', shadowCss(primary.shadow)],
    ['primary-radius', `${primary.radius}px`],
    ['secondary-bg', gradientCss(secondary.swirl)],
    ['secondary-text', secondary.text.color],
    ['secondary-weight', String(secondary.text.weight)],
    ['secondary-border', `${secondary.border.width}px solid ${secondary.border.color}`],
    ['secondary-shadow', shadowCss(secondary.shadow)],
    ['secondary-radius', `${secondary.radius}px`],
    ['card-bg', card.fill],
    ['card-border', `${card.border.width}px solid ${card.border.color}`],
    ['card-shadow', shadowCss(card.shadow)],
    ['card-radius', `${card.radius}px`],
    ['settle-ms', `${primary.settleMs}ms`],
  ];
  return lines.map(([name, value]) => `  --gg-${name}: ${value};`);
}

/** The CSS text for marketing: one `:root` block of plain `--gg-*` custom properties. */
export function toMarketingCss(v2: MarketingInput): string {
  return block(':root', marketingLines(v2));
}

/** The whole text of apps/marketing/src/styles/tokens.generated.css. */
export function toMarketingFile(v2: MarketingInput): string {
  return generatedHeader + toMarketingCss(v2);
}

/** The web font stack for the v2 family: the brand font, then system fonts. */
export function webFontStack(p: Pick<Primitives, 'font'>): string {
  return `'${p.font.family}', system-ui, -apple-system, 'Segoe UI', sans-serif`;
}

/** `--font-v2` and the v2 colours (Tailwind reads these). Every name starts `v2`, so none meets a v1 name. Ink is the one name without v2: it is `--color-text`, which no v1 colour uses. */
export function webV2ThemeLines({ primitives, roles, recipes }: WebV2Input): string[] {
  const { primary, secondary } = recipes.button;
  const { card, nudge, field } = recipes;
  const lines: Array<[string, string]> = [
    ['font-v2', webFontStack(primitives)],
    ['color-text', roles.ink],
    ['color-v2-page', roles.page.color],
    ['color-v2-glow-sun', roles.page.glows.topRight],
    ['color-v2-glow-sky', roles.page.glows.bottomLeft],
    ['color-v2-heading', roles.heading.color],
    ['color-v2-eyebrow', roles.eyebrow.color],
    ['color-v2-link', roles.link],
    ['color-v2-wash', roles.wash],
    ['color-v2-muted', roles.muted],
    ['color-v2-muted-strong', roles.mutedStrong],
    ['color-v2-divider', roles.divider],
    ['color-v2-error', roles.error],
    ['color-v2-success', roles.success],
    ['color-v2-focus', roles.focus],
    ['color-v2-field-fill', field.fill],
    ['color-v2-field-edge', field.edge],
    ['color-v2-field-focus', field.focusRing],
    ['color-v2-primary-text', primary.text.color],
    ['color-v2-primary-border', primary.border.color],
    ['color-v2-secondary-text', secondary.text.color],
    ['color-v2-secondary-border', secondary.border.color],
    ['color-v2-card-fill', card.fill],
    ['color-v2-card-border', card.border.color],
    ['color-v2-nudge-text', nudge.text.color],
    ['color-v2-nudge-border', nudge.border.color],
    ...nudge.speckles.colors.map((color, i): [string, string] => [`color-v2-nudge-speckle-${i + 1}`, color]),
    ['color-v2-open-ring', roles.doneMark.openRing],
  ];
  return lines.map(([name, value]) => `  --${name}: ${value};`);
}

/** The v2 gradients, shadows, radius, border widths and motion times, as plain custom properties. */
export function webV2RootLines({ primitives, roles, recipes }: WebV2Input): string[] {
  const { primary, secondary } = recipes.button;
  const { card, nudge } = recipes;
  const lines: Array<[string, string]> = [
    ['primary-bg', gradientCss(primary.swirl)],
    ['secondary-bg', gradientCss(secondary.swirl)],
    ['nudge-bg', gradientCss(nudge.swirl)],
    ['primary-shadow', shadowCss(primary.shadow)],
    ['secondary-shadow', shadowCss(secondary.shadow)],
    ['card-shadow', shadowCss(card.shadow)],
    ['nudge-shadow', shadowCss(nudge.shadow)],
    ['nudge-speckle-alpha', String(nudge.speckles.alpha)],
    ['nudge-orb', conicCss(nudge.orb.conic)],
    ['nudge-orb-size', `${nudge.orb.size}px`],
    // One pass of the orb: settle time of a full turn, never more than one turn (the cap mobile's ConicSwirl uses).
    ['nudge-orb-turn', oneTurnDeg(primary.settleMs, roles.doneMark.spinMs)],
    // The done mark on a ticked checklist row: a 16px conic swirl that turns once (same cap as the orb), and the open ring's width.
    ['done-mark-size', `${roles.doneMark.size}px`],
    ['done-mark-ring-width', `${roles.doneMark.openWidth}px`],
    ['done-mark-swirl', conicCss(roles.doneMark.swirl)],
    ['done-mark-turn', oneTurnDeg(primary.settleMs, roles.doneMark.spinMs)],
    ['radius', `${card.radius}px`],
    ['border-thin', `${primitives.border.thin}px`],
    ['border-medium', `${primitives.border.medium}px`],
    ['body-size', `${roles.body.size}px`],
    ['eyebrow-size', `${roles.eyebrow.size}px`],
    ['eyebrow-tracking', `${roles.eyebrow.tracking}em`],
    ['heading-weight', String(roles.heading.weight)],
    ['weight-light', String(primitives.font.weights.light)],
    ['weight-regular', String(primitives.font.weights.regular)],
    ['weight-medium', String(primitives.font.weights.medium)],
    // JS should read these times from @griever/tokens: the minifier rewrites 4500ms to 4.5s.
    ['drift-ms', `${primary.driftMs}ms`],
    ['settle-ms', `${primary.settleMs}ms`],
    ['spin-ms', `${roles.doneMark.spinMs}ms`],
  ];
  return lines.map(([name, value]) => `  --v2-${name}: ${value};`);
}
