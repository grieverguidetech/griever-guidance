// Writes apps/web/src/theme.generated.css from the built @griever/tokens (run `nx build tokens`
// first; the nx target `tokens:generate-css` does). Plain node, no tsx.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { colors, fontSerifStack, radius, spacing, toWebThemeCss } from '../../libs/tokens/dist/index.js';

const header = `/* GENERATED by tools/scripts/generate-token-css.mjs from libs/tokens. Do not edit.
   Change libs/tokens, then run: pnpm nx run tokens:generate-css */\n\n`;

const out = join(import.meta.dirname, '../../apps/web/src/theme.generated.css');
writeFileSync(out, header + toWebThemeCss({ colors, fontSerifStack, spacing, radius }));
console.log(`wrote ${out}`);
